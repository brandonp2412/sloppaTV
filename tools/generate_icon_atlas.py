cell = 96
rows = (len(paths) + 3) // 4
atlas = Image.new("L", (cell * 4, cell * rows))
for index, path in enumerate(paths):
    svg = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><g transform="translate(1 1) scale(0.916666667)" fill="none" stroke="white" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">{path}</g></svg>'
    png = cairosvg.svg2png(bytestring=svg.encode(), output_width=cell * 4, output_height=cell * 4)
    mask = Image.open(io.BytesIO(png)).getchannel("A").resize((cell, cell), Image.Resampling.LANCZOS)
    atlas.paste(mask, ((index % 4) * cell, (index // 4) * cell))
runs = []
for value, group in groupby(atlas.tobytes()):
    count = sum(1 for _ in group)
    while count:
        chunk = min(count, 255)
        runs.extend((chunk, value))
        count -= chunk
